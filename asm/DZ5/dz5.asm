.data
# Таблица кодов для семисегментного индикатора
digit_codes:
    .byte 0x3F  # 0
    .byte 0x06  # 1
    .byte 0x5B  # 2
    .byte 0x4F  # 3
    .byte 0x66  # 4
    .byte 0x6D  # 5
    .byte 0x7D  # 6
    .byte 0x07  # 7
    .byte 0x7F  # 8
    .byte 0x6F  # 9
    .byte 0x77  # A
    .byte 0x7C  # b
    .byte 0x39  # C
    .byte 0x5E  # d
    .byte 0x79  # E
    .byte 0x71  # F

.text
.globl main

# Подпрограмма для вывода цифры на индикатор
# a0 - цифра для вывода (0-15)
# a1 - адрес индикатора (0 для правого, 1 для левого)
print_digit:
    # Сохраняем регистры в стек
    addi sp, sp, -16
    sw ra, 0(sp)
    sw s0, 4(sp)
    sw s1, 8(sp)
    sw s2, 12(sp)
    
    # Сохраняем параметры
    mv s0, a0  # Сохраняем цифру
    mv s1, a1  # Сохраняем тип индикатора
    
    # Оставляем только младшие 4 бита
    andi s0, s0, 0x0F
    
    # Получаем код для семисегментного индикатора
    la t0, digit_codes
    add t0, t0, s0
    lb t1, 0(t0)  # Загружаем код сегментов
    
    # Если цифра > 9, добавляем точку
    li t2, 9
    ble s0, t2, no_dot
    ori t1, t1, 0x80  # Устанавливаем старший бит (точка)
    
no_dot:
    # Загружаем базовый адрес MMIO
    lui t2, 0xFFFF0
    
    # Определяем смещение для индикатора
    beqz s1, right_ind
    # Левый индикатор: 0xFFFF0011
    sb t1, 0x11(t2)
    j end_print
    
right_ind:
    # Правый индикатор: 0xFFFF0010  
    sb t1, 0x10(t2)
    
end_print:
    # Восстанавливаем регистры
    lw ra, 0(sp)
    lw s0, 4(sp)
    lw s1, 8(sp)
    lw s2, 12(sp)
    addi sp, sp, 16
    ret

main:
    # Инициализация
    li s2, 0  # Счетчик значений (0-15)
    
main_loop:
    # Выводим текущее значение на ЛЕВЫЙ индикатор (a1 = 1)
    li a1, 1              # 1 = левый индикатор
    mv a0, s2             # Текущее значение
    jal print_digit
    
    # Задержка 1 секунда (1000 мс)
    li a0, 1000
    li a7, 32
    ecall
    
    # Выводим текущее значение на ПРАВЫЙ индикатор (a1 = 0)
    li a1, 0              # 0 = правый индикатор
    mv a0, s2             # Текущее значение
    jal print_digit
    
    # Задержка 1 секунда (1000 мс)
    li a0, 1000
    li a7, 32
    ecall
    
    # Увеличиваем счетчик
    addi s2, s2, 1
    
    # Проверяем, не превысили ли 15
    li t0, 16
    blt s2, t0, main_loop
    
    # Если достигли 16, сбрасываем на 0
    li s2, 0
    j main_loop